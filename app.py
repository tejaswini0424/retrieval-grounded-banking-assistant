import hashlib
import hmac
import json
import os
import re
import secrets
import sqlite3
import time
from contextlib import closing
from http import HTTPStatus
from http.cookies import SimpleCookie, CookieError
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DB = Path(os.environ.get("BANK_DB", ROOT / "banking.sqlite3"))
DATABASE_URL = os.environ.get("DATABASE_URL")
KNOWLEDGE = json.loads((ROOT / "knowledge.json").read_text(encoding="utf-8"))
SESSION_SECONDS = 8 * 3600
PASSWORD_ROUNDS = 600_000
DUMMY_SALT = bytes(16)
FOLLOW_UP = re.compile(r"^(what (if|about)|how (long|do i)|and\b|can i|then\b|it\b|why\b|when\b)", re.I)
SENSITIVE = re.compile(r"(?<!\d)(?:\d[ -]?){12,19}(?!\d)|\b(?:otp|pin|password|cvv|one.time code)\s*(?:is|[:=])\s*\S+", re.I)


def connect():
    if DATABASE_URL:
        return PostgresConnection()
    db = sqlite3.connect(DB, timeout=10)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    return db


class PostgresConnection:
    def __init__(self):
        import psycopg
        from psycopg.rows import dict_row

        self.connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=8)

    def execute(self, sql, parameters=()):
        if sql == "BEGIN IMMEDIATE":
            return self.connection.execute("SELECT pg_advisory_xact_lock(9201250)")
        return self.connection.execute(sql.replace("?", "%s"), parameters)

    def commit(self):
        self.connection.commit()

    def close(self):
        self.connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.connection.rollback()


def initialize():
    with closing(connect()) as db, db:
        schema = """
            CREATE TABLE IF NOT EXISTS users (
                id {identity}, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL,
                salt {binary} NOT NULL, password_hash {binary} NOT NULL
            );
            CREATE TABLE IF NOT EXISTS sessions (
                digest TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
                expires INTEGER NOT NULL
            );
            CREATE TABLE IF NOT EXISTS sources (id TEXT PRIMARY KEY);
            CREATE TABLE IF NOT EXISTS turns (
                id {identity}, user_id INTEGER NOT NULL REFERENCES users(id),
                question TEXT NOT NULL, answer TEXT NOT NULL, source TEXT REFERENCES sources(id)
            );
            CREATE INDEX IF NOT EXISTS turns_user ON turns(user_id, id);
            CREATE TABLE IF NOT EXISTS auth_limits (
                address TEXT PRIMARY KEY, "window" INTEGER NOT NULL, attempts INTEGER NOT NULL
            );
        """
        if DATABASE_URL:
            db.execute("SELECT pg_advisory_xact_lock(9201251)")
        ddl = schema.format(
            identity="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if DATABASE_URL else "INTEGER PRIMARY KEY",
            binary="BYTEA" if DATABASE_URL else "BLOB",
        )
        for statement in ddl.split(";"):
            if statement.strip():
                db.execute(statement)
        for source in KNOWLEDGE:
            db.execute("INSERT INTO sources VALUES (?) ON CONFLICT DO NOTHING", (source["id"],))


def password_hash(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), salt, PASSWORD_ROUNDS)


def digest(token):
    return hashlib.sha256(token.encode()).hexdigest()


def retrieve(question, previous=None):
    words = set(re.findall(r"[a-z]+", question.lower()))
    scores = [len(words.intersection(doc["keywords"].split())) for doc in KNOWLEDGE]
    best = max(scores)
    if previous and FOLLOW_UP.match(question) and best <= 1:
        source = next((doc for doc in KNOWLEDGE if doc["id"] == previous), None)
        if source:
            return source["answer"], source["id"]
    if best and scores.count(best) == 1:
        source = KNOWLEDGE[scores.index(best)]
        return source["answer"], source["id"]
    return ("I couldn’t find a clear match in the support library. Try naming the issue, "
            "such as a lost card, pending transfer, or an unrecognized transaction. "
            "For account-specific help, use your bank’s official support channel."), None


class Handler(BaseHTTPRequestHandler):
    def respond(self, status, value, cookie=None):
        body = json.dumps(value).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        if cookie:
            self.send_header("Set-Cookie", cookie)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def fail(self, status, message):
        self.respond(status, {"error": message})

    def token(self):
        try:
            cookies = SimpleCookie(self.headers.get("Cookie", ""))
            return cookies["bank_session"].value if "bank_session" in cookies else ""
        except CookieError:
            return ""

    def client_ip(self):
        if os.environ.get("VERCEL"):
            forwarded = self.headers.get("X-Vercel-Forwarded-For")
            if forwarded:
                return forwarded
        return self.client_address[0]

    def cookie(self, token="", age=0):
        secure = "; Secure" if os.environ.get("VERCEL") or os.environ.get("BANK_SECURE_COOKIE") == "1" else ""
        return f"bank_session={token}; Max-Age={age}; Path=/; HttpOnly; SameSite=Strict{secure}"

    def user(self, db):
        return db.execute("""
            SELECT users.id, name, email FROM sessions JOIN users ON users.id = sessions.user_id
            WHERE digest = ? AND expires > ?
        """, (digest(self.token()), int(time.time()))).fetchone()

    def do_GET(self):
        if self.path in ("/", "/style.css", "/dashboard.js"):
            filename, content_type = {
                "/": ("index.html", "text/html; charset=utf-8"),
                "/style.css": ("style.css", "text/css"),
                "/dashboard.js": ("dashboard.js", "text/javascript"),
            }[self.path]
            body = (ROOT / "web" / filename).read_bytes()
            self.send_response(200)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Content-Security-Policy", "default-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'self'")
            self.end_headers()
            self.wfile.write(body)
            return
        if self.path == "/api/sources":
            self.respond(200, [{k: doc[k] for k in ("id", "title", "answer")} for doc in KNOWLEDGE])
            return
        with closing(connect()) as db:
            user = self.user(db)
            if self.path == "/api/session":
                self.respond(200, {"user": dict(user) if user else None})
            elif self.path == "/api/chat":
                if not user:
                    self.fail(401, "Log in to view your conversation.")
                    return
                rows = db.execute("""
                    SELECT question, answer, source FROM turns WHERE user_id = ?
                    ORDER BY id DESC LIMIT 100
                """, (user["id"],)).fetchall()
                self.respond(200, [dict(row) for row in reversed(rows)])
            else:
                self.fail(404, "Page unavailable.")

    def do_POST(self):
        if self.headers.get("Sec-Fetch-Site") in ("cross-site", "same-site"):
            return self.fail(403, "Use the dashboard to submit this request.")
        if self.headers.get_content_type() != "application/json":
            return self.fail(415, "Use JSON.")
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 8192:
                return self.fail(413, "Invalid request size.")
            data = json.loads(self.rfile.read(length))
            if not isinstance(data, dict):
                raise ValueError
        except (ValueError, UnicodeError):
            return self.fail(400, "Invalid request.")
        with closing(connect()) as db, db:
            if self.path in ("/api/register", "/api/login"):
                return self.authenticate(db, data)
            if self.path == "/api/logout":
                db.execute("DELETE FROM sessions WHERE digest = ?", (digest(self.token()),))
                db.commit()
                return self.respond(200, {"user": None}, self.cookie())
            if self.path not in ("/api/chat", "/api/chat/clear"):
                return self.fail(404, "Page unavailable.")
            db.execute("BEGIN IMMEDIATE")
            user = self.user(db)
            if not user:
                return self.fail(401, "Log in to use the assistant.")
            if self.path == "/api/chat/clear":
                db.execute("DELETE FROM turns WHERE user_id = ?", (user["id"],))
                db.commit()
                return self.respond(200, [])
            question = data.get("question")
            if not isinstance(question, str) or not 1 <= len(question.strip()) <= 500:
                return self.fail(400, "Enter a question of 1 to 500 characters.")
            question = question.strip()
            if SENSITIVE.search(question):
                return self.fail(400, "Remove any card number, password, PIN, or security code before sending.")
            previous = db.execute("SELECT source FROM turns WHERE user_id = ? ORDER BY id DESC LIMIT 1", (user["id"],)).fetchone()
            answer, source = retrieve(question, previous["source"] if previous else None)
            db.execute("INSERT INTO turns(user_id, question, answer, source) VALUES (?, ?, ?, ?)",
                       (user["id"], question, answer, source))
            db.commit()
            return self.respond(200, {"question": question, "answer": answer, "source": source})

    def authenticate(self, db, data):
        email, password = data.get("email"), data.get("password")
        if not isinstance(email, str) or not isinstance(password, str):
            return self.fail(400, "Enter your email and password.")
        email = email.strip().lower()
        if len(email) > 254 or not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email) or not 12 <= len(password) <= 128:
            return self.fail(400, "Use a valid email and a password of 12 to 128 characters.")
        now = int(time.time())
        address = self.client_ip()
        db.execute('DELETE FROM auth_limits WHERE "window" <= ?', (now - 300,))
        row = db.execute("""
            INSERT INTO auth_limits VALUES (?, ?, 1)
            ON CONFLICT(address) DO UPDATE SET attempts = auth_limits.attempts + 1
            WHERE auth_limits.attempts < 12 RETURNING attempts
        """, (address, now)).fetchone()
        db.commit()
        if row is None:
            return self.fail(429, "Too many attempts. Try again in a few minutes.")
        if self.path == "/api/register":
            name = data.get("name")
            if not isinstance(name, str) or not 1 <= len(name.strip()) <= 80:
                return self.fail(400, "Enter a name of 1 to 80 characters.")
            salt = secrets.token_bytes(16)
            hashed = password_hash(password, salt)
            created = db.execute("""
                INSERT INTO users(name,email,salt,password_hash) VALUES (?,?,?,?)
                ON CONFLICT(email) DO NOTHING RETURNING id
            """, (name.strip(), email, salt, hashed)).fetchone()
            if created is None:
                return self.fail(409, "Could not create an account with that email.")
            user_id = created["id"]
        else:
            user = db.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
            candidate = password_hash(password, user["salt"] if user else DUMMY_SALT)
            if not user or not hmac.compare_digest(candidate, user["password_hash"]):
                return self.fail(401, "Email or password is incorrect.")
            user_id = user["id"]
        token = secrets.token_urlsafe(32)
        db.execute("DELETE FROM sessions WHERE expires <= ? OR digest = ?", (now, digest(self.token())))
        db.execute("INSERT INTO sessions VALUES (?, ?, ?)", (digest(token), user_id, now + SESSION_SECONDS))
        profile = db.execute("SELECT id,name,email FROM users WHERE id = ?", (user_id,)).fetchone()
        db.commit()
        status = HTTPStatus.CREATED if self.path == "/api/register" else HTTPStatus.OK
        self.respond(status, {"user": dict(profile)}, self.cookie(token, SESSION_SECONDS))


if __name__ == "__main__":
    initialize()
    host = os.environ.get("BANK_HOST", "127.0.0.1")
    port = int(os.environ.get("BANK_PORT", "8000"))
    with ThreadingHTTPServer((host, port), Handler) as server:
        print(f"Banking assistant running at http://{host}:{port}", flush=True)
        server.serve_forever()
